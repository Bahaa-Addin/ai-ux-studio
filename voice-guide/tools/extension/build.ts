/**
 * Builds the public demo extension (ADR-0056): one MV3 extension for Chrome/Edge (dist/chrome) and
 * Firefox desktop and Android (dist/firefox), that runs the shared loader (packages/loader, the same
 * code the demo browser injects) at document_start in the page's own world on the site's origins,
 * pointed at a public gateway (ADR-0053).
 *
 *   npm run extension:build -- --gateway https://vg-public-demo-<project-number>.europe-west1.run.app [--site vodafone-eg] [--out extension/dist]
 *
 * Then zip each folder's contents for the store: cd extension/dist/chrome && zip -r ../chrome.zip .
 * No keys or secrets go into the extension: the site key is public (it only names the site).
 */
import fs from 'node:fs'
import path from 'node:path'
import { parseArgs } from 'node:util'
import { crc32, deflateSync } from 'node:zlib'

import { loadSiteConfig, ROOT, type SiteConfig } from '#shared/config.ts'

import { loaderScript } from '../../packages/loader/src/loader.ts'
import { loaderExperiences } from '../demo-browser.ts'

export const NAME = 'Voice guide preview (independent prototype)'
export const VERSION = '0.1.0'

export interface BuildOptions {
	site: SiteConfig
	gateway: string
	out: string
	version?: string
}

/** The manifest for one browser. Host permissions are the site's origins only. */
export function manifest(browser: 'chrome' | 'firefox', site: SiteConfig, version = VERSION): Record<string, unknown> {
	const hosts = site.origins.map((o) => `${new URL(o.url).origin}/*`)
	return {
		manifest_version: 3,
		name: NAME,
		short_name: 'Voice guide preview',
		version,
		description: 'An independent prototype: a voice guide and demo experiences on the site’s public pages. Not affiliated with the site’s owner.',
		permissions: ['scripting', 'storage'],
		host_permissions: hosts,
		action: { default_title: 'Voice guide preview', default_popup: 'popup.html', default_icon: { 16: 'icons/16.png', 48: 'icons/48.png', 128: 'icons/128.png' } },
		icons: { 16: 'icons/16.png', 48: 'icons/48.png', 128: 'icons/128.png' },
		...(browser === 'chrome'
			? { background: { service_worker: 'background.js' }, minimum_chrome_version: '111' }
			: {
					background: { scripts: ['background.js'] },
					browser_specific_settings: { gecko: { id: 'voice-guide-preview@aixc.invalid', strict_min_version: '128.0', data_collection_permissions: { required: ['websiteContent'] } }, gecko_android: { strict_min_version: '128.0' } },
				}),
	}
}

/** The loader the extension injects: the site's origins, the public gateway, server-sent events. */
export function extensionLoader(site: SiteConfig, gateway: string): string {
	return `// Generated by tools/extension/build.ts from packages/loader (ADR-0053, ADR-0056). Do not edit.\n${loaderScript({ siteKey: site.siteKey, origins: site.origins.map((o) => new URL(o.url).origin), gateway, xray: 'off', experiences: loaderExperiences({ site }) })}\n`
}

export function buildExtension(o: BuildOptions): { dirs: string[] } {
	const gateway = o.gateway.replace(/\/$/, '')
	const u = new URL(gateway)
	if (u.protocol !== 'https:' && !['127.0.0.1', 'localhost'].includes(u.hostname)) throw new Error(`--gateway must be https:// (got ${gateway})`)
	const src = path.join(ROOT, 'extension/src')
	const matches = o.site.origins.map((x) => `${new URL(x.url).origin}/*`)
	const start = o.site.crawl.start[0]
	const dirs: string[] = []
	for (const browser of ['chrome', 'firefox'] as const) {
		const dir = path.join(o.out, browser)
		fs.rmSync(dir, { recursive: true, force: true })
		fs.mkdirSync(path.join(dir, 'icons'), { recursive: true })
		fs.writeFileSync(path.join(dir, 'manifest.json'), `${JSON.stringify(manifest(browser, o.site, o.version), null, 2)}\n`)
		fs.writeFileSync(path.join(dir, 'loader.js'), extensionLoader(o.site, gateway))
		fs.writeFileSync(path.join(dir, 'background.js'), fs.readFileSync(path.join(src, 'background.js'), 'utf8').replace('__MATCHES__', JSON.stringify(matches)))
		fs.writeFileSync(path.join(dir, 'popup.js'), fs.readFileSync(path.join(src, 'popup.js'), 'utf8').replace('__START__', JSON.stringify(start)).replace('__GATEWAY__', JSON.stringify(gateway)))
		fs.copyFileSync(path.join(src, 'popup.html'), path.join(dir, 'popup.html'))
		for (const size of [16, 48, 128]) fs.writeFileSync(path.join(dir, 'icons', `${size}.png`), icon(size))
		dirs.push(dir)
	}
	return { dirs }
}

/** A plain icon (a white microphone dot on a dark disc), drawn here so no image is committed. */
export function icon(size: number): Buffer {
	const px = Buffer.alloc(size * (size * 4 + 1))
	const c = (size - 1) / 2
	for (let y = 0; y < size; y++) {
		px[y * (size * 4 + 1)] = 0
		for (let x = 0; x < size; x++) {
			const d = Math.hypot(x - c, y - c) / (size / 2)
			const i = y * (size * 4 + 1) + 1 + x * 4
			const inDisc = d <= 0.98
			const inDot = Math.hypot(x - c, (y - c) * 0.75) / (size / 2) <= 0.32
			const [r, g, b] = inDot ? [255, 255, 255] : [20, 24, 28]
			px[i] = r
			px[i + 1] = g
			px[i + 2] = b
			px[i + 3] = inDisc ? 255 : 0
		}
	}
	const chunk = (type: string, data: Buffer) => {
		const len = Buffer.alloc(4)
		len.writeUInt32BE(data.length)
		const td = Buffer.concat([Buffer.from(type, 'ascii'), data])
		const crc = Buffer.alloc(4)
		crc.writeUInt32BE(crc32(td) >>> 0)
		return Buffer.concat([len, td, crc])
	}
	const ihdr = Buffer.alloc(13)
	ihdr.writeUInt32BE(size, 0)
	ihdr.writeUInt32BE(size, 4)
	ihdr[8] = 8
	ihdr[9] = 6
	return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(px)), chunk('IEND', Buffer.alloc(0))])
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
	const { values } = parseArgs({ options: { gateway: { type: 'string' }, site: { type: 'string', default: 'vodafone-eg' }, out: { type: 'string', default: path.join(ROOT, 'extension/dist') }, version: { type: 'string' } }, strict: true })
	if (!values.gateway) throw new Error('--gateway <https://...> is required: the public gateway the extension talks to (ADR-0053)')
	const site = loadSiteConfig(path.join(ROOT, 'config/sites', `${values.site}.yaml`))
	const { dirs } = buildExtension({ site, gateway: values.gateway, out: path.resolve(values.out), version: values.version })
	for (const d of dirs) console.log(`Built ${path.relative(ROOT, d)}`)
	console.log('Chrome/Edge: chrome://extensions → Developer mode → Load unpacked → extension/dist/chrome')
	console.log('Firefox: about:debugging#/runtime/this-firefox → Load Temporary Add-on → extension/dist/firefox/manifest.json')
}
