/**
 * The Render Blueprint (render.yaml at the repository root, ADR-0067): each setting of the free web
 * service and the free Postgres, no secret value in the file, and the plain settings pass the gateway's
 * own public start-up checks (ADR-0053 §2). Reads files only; nothing calls Render.
 */
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { test } from 'node:test'

import { parse } from 'yaml'

import { checkPublicConfig, loadPlatformConfig, ROOT } from '#shared/config.ts'

import { RATE_TURNS_PER_MIN } from '../../tools/check-public-gateway.ts'

const REPO = path.resolve(ROOT, '..')

interface EnvVar {
	key: string
	value?: unknown
	generateValue?: boolean
	sync?: boolean
	fromDatabase?: { name: string; property: string }
}
interface Blueprint {
	services: { type: string; name: string; runtime: string; plan: string; region: string; branch: string; dockerfilePath: string; dockerContext: string; healthCheckPath: string; autoDeployTrigger: unknown; envVars: EnvVar[] }[]
	databases: { name: string; plan: string; region: string; postgresMajorVersion: unknown; databaseName: string; user: string; ipAllowList: unknown }[]
}

const bp = parse(fs.readFileSync(path.join(REPO, 'render.yaml'), 'utf8')) as Blueprint
const [web] = bp.services
const [db] = bp.databases
const byKey = new Map(web.envVars.map((e) => [e.key, e]))
const SECRETS = ['VG_SECRET', 'VG_ADMIN_TOKEN', 'ANTHROPIC_API_KEY', 'VG_WHISPER_URL', 'VG_WHISPER_TOKEN', 'VG_VOICETUT_URL']

const PLAIN: Record<string, string> = {
	PORT: '8080',
	VG_STORE: 'postgres',
	VG_KB_SEED: 'committed',
	VG_CLIENT_IP_HEADER: 'cf-connecting-ip',
	VG_PUBLIC: 'on',
	VG_TRAIL: 'on',
	VG_LLM_PROVIDER: 'anthropic',
	VG_LLM_EFFORT: 'low',
	VG_AGENT_TOKENS_PER_SITE_DAY: '3000000',
	VG_VOICETUT_SENTENCES_PER_DAY: '300',
	VG_STT_SECONDS_PER_DAY: '14400',
	VG_RATE_TURNS_PER_MIN: '20',
	VG_DB_POOL_MAX: '5',
	VG_EXTRA_ORIGINS: 'https://bahaa-addin.github.io',
}

test('one free Docker web service, built from the gateway Dockerfile at the repository root, deployed by hand', () => {
	assert.equal(bp.services.length, 1)
	assert.equal(web.type, 'web')
	assert.equal(web.name, 'vg-public-demo')
	assert.equal(web.runtime, 'docker')
	assert.equal(web.plan, 'free')
	assert.equal(web.region, 'frankfurt')
	assert.equal(web.branch, 'feature/live-way2')
	assert.equal(web.dockerfilePath, './voice-guide/deploy/gateway/gateway.Dockerfile')
	assert.ok(fs.existsSync(path.join(REPO, web.dockerfilePath)), 'the Dockerfile exists')
	assert.ok(fs.existsSync(path.join(REPO, `${web.dockerfilePath}.dockerignore`)), 'and its ignore file beside it')
	assert.equal(web.dockerContext, '.')
	assert.equal(web.healthCheckPath, '/health')
	assert.equal(web.autoDeployTrigger, 'off', 'a string, not YAML 1.1’s boolean false')
})

test('the plain settings, as strings; PORT is the image’s VG_PORT; the check tool knows the turn rate', () => {
	const plain = Object.fromEntries(web.envVars.filter((e) => 'value' in e).map((e) => [e.key, e.value]))
	assert.deepEqual(plain, PLAIN)
	for (const [k, v] of Object.entries(plain)) assert.equal(typeof v, 'string', `${k} is a string`)
	const dockerfile = fs.readFileSync(path.join(REPO, web.dockerfilePath), 'utf8')
	assert.equal(plain.PORT, dockerfile.match(/\bVG_PORT=(\d+)/)?.[1])
	assert.equal(Number(plain.VG_RATE_TURNS_PER_MIN), RATE_TURNS_PER_MIN)
	assert.ok(!byKey.has('VG_PUBLIC_URL'), 'VG_PUBLIC_URL comes from RENDER_EXTERNAL_URL')
	assert.equal(web.envVars.length, byKey.size, 'no key twice')
})

test('secrets: generated by Render or entered in its dashboard, never a value in the file', () => {
	for (const k of SECRETS) {
		const e = byKey.get(k)
		assert.ok(e, `${k} is declared`)
		assert.ok(!('value' in e), `${k} holds no value`)
	}
	assert.equal(byKey.get('VG_SECRET')!.generateValue, true)
	assert.equal(byKey.get('VG_ADMIN_TOKEN')!.generateValue, true)
	for (const k of ['ANTHROPIC_API_KEY', 'VG_WHISPER_URL', 'VG_WHISPER_TOKEN', 'VG_VOICETUT_URL']) assert.equal(byKey.get(k)!.sync, false, `${k} is asked for in the dashboard`)
	assert.deepEqual(byKey.get('DATABASE_URL')!.fromDatabase, { name: db.name, property: 'connectionString' })
})

test('one free Postgres in the service’s region, reachable only from Render’s private network', () => {
	assert.equal(bp.databases.length, 1)
	assert.equal(db.name, 'vg-public-db')
	assert.equal(db.plan, 'free')
	assert.equal(db.region, web.region)
	assert.equal(db.postgresMajorVersion, '16')
	assert.equal(db.databaseName, 'voiceguide')
	assert.equal(db.user, 'voiceguide')
	assert.deepEqual(db.ipAllowList, [], 'an empty list, not omitted (omitted allows every address)')
})

test("the Blueprint's settings pass the gateway's own public checks; without the secrets it would refuse to start", () => {
	const env = { ...PLAIN, VG_SECRET: 'x'.repeat(44), VG_ADMIN_TOKEN: 'y'.repeat(44), ANTHROPIC_API_KEY: 'sk-dummy', RENDER_EXTERNAL_URL: 'https://vg-public-demo.onrender.com', DATABASE_URL: 'postgres://voiceguide@dpg-x/voiceguide' } as unknown as NodeJS.ProcessEnv
	const p = loadPlatformConfig(env)
	assert.deepEqual(checkPublicConfig(p, env), [])
	assert.equal(p.publicUrl, 'https://vg-public-demo.onrender.com')
	assert.equal(p.port, 4400, 'the gateway reads VG_PORT (8080 in the image), not PORT')
	assert.equal(p.store, 'postgres')
	assert.equal(p.dbPoolMax, 5)
	assert.equal(p.clientIpHeader, 'cf-connecting-ip')
	assert.equal(p.rateLimit.turnsPerMinute, 20)
	for (const k of ['VG_SECRET', 'VG_ADMIN_TOKEN', 'ANTHROPIC_API_KEY']) {
		const without = { ...env } as Record<string, unknown>
		delete without[k]
		assert.ok(checkPublicConfig(loadPlatformConfig(without as NodeJS.ProcessEnv), without as NodeJS.ProcessEnv).length, `refuses without ${k}`)
	}
	const empty = { ...env, VG_WHISPER_URL: '', VG_WHISPER_TOKEN: '', VG_VOICETUT_URL: '' } as unknown as NodeJS.ProcessEnv
	assert.deepEqual(checkPublicConfig(loadPlatformConfig(empty), empty), [], 'the optional ones left empty are fine')
	assert.equal(loadPlatformConfig(empty).voicetut.url, undefined, 'an empty VoiceTut URL is unset')
})
